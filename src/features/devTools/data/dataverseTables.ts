export type TableGroup = 'Core ticket' | 'Charges & ledgers' | 'Platform'

export interface TableColumnDoc {
  name: string
  note: string
}

export interface TableUsageDoc {
  /** Where in the app / process the table is touched. */
  where: string
  /** What happens to the table there. */
  how: string
}

export interface DataverseTableDoc {
  id: string
  displayName: string
  group: TableGroup
  logicalName: string
  entitySet: string
  generatedService: string
  serviceFile: string
  purpose: string
  /** Column that ties this table back to the closing ticket (business key, not GUID). */
  linkedBy: string
  access: {
    appReads: string
    appWrites: string
    automationWrites: string
  }
  auditLogged: boolean
  keyColumns: TableColumnDoc[]
  usage: TableUsageDoc[]
  /** TDD / PDD guidance: what to assert, mock or preserve when changing this table's behaviour. */
  testingNotes: string[]
}

export interface ProcessStageDoc {
  stage: string
  trigger: string
  tablesTouched: Array<{ tableId: string; effect: string }>
}

